// Collects every captured scene into src/captures.generated.ts for the composition.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const dir = path.join(root, "public/captures");
const scenes = {};
for (const name of fs.existsSync(dir) ? fs.readdirSync(dir).sort() : []) {
    const file = path.join(dir, name, "scene.json");
    if (fs.existsSync(file)) {
        scenes[name] = JSON.parse(fs.readFileSync(file, "utf8"));
    }
}
const out = `// Generated by capture/manifest.mjs. Do not edit.
export type CaptureFrame = { t: number; file: string; label: string };
export type CaptureScene = {
    name: string;
    frames: CaptureFrame[];
    marks: Record<string, number>;
    [extra: string]: any;
};
export const Captures: Record<string, CaptureScene> = ${JSON.stringify(scenes, null, 1)};
`;
fs.writeFileSync(path.join(root, "src/captures.generated.ts"), out);
console.log("scenes:", Object.keys(scenes).join(", ") || "(none)");
